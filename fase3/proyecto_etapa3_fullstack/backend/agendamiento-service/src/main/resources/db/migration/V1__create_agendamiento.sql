CREATE TABLE IF NOT EXISTS db_agendamiento.reservas (
    reserva_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id BIGINT,
    plan_id VARCHAR(100) NOT NULL,
    servicio VARCHAR(255) NOT NULL,
    precio INTEGER NOT NULL,
    nutricionista_id BIGINT NOT NULL,
    nutricionista_nombre VARCHAR(255) NOT NULL,
    fecha VARCHAR(20) NOT NULL,
    hora VARCHAR(10) NOT NULL,
    motivo VARCHAR(255) NOT NULL,
    estado VARCHAR(50) NOT NULL DEFAULT 'CONFIRMADA',
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

