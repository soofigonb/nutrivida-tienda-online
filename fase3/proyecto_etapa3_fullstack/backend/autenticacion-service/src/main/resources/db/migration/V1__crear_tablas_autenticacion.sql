-- Tabla de roles.
CREATE TABLE db_autenticacion.rol (
    -- Identificador autogenerado.
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Nombre obligatorio.
    nombre VARCHAR(30) NOT NULL,
    -- Impide duplicados.
    CONSTRAINT uk_rol_nombre UNIQUE (nombre)
);

-- Tabla de estados.
CREATE TABLE db_autenticacion.estado_usuario (
    -- Identificador autogenerado.
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Nombre obligatorio.
    nombre VARCHAR(30) NOT NULL,
    -- Impide duplicados.
    CONSTRAINT uk_estado_usuario_nombre UNIQUE (nombre)
);

-- Tabla de usuarios.
CREATE TABLE db_autenticacion.usuario (
    -- Identificador único.
    id UUID PRIMARY KEY,
    -- Correo de acceso.
    correo VARCHAR(100) NOT NULL,
    -- Hash BCrypt.
    password_hash VARCHAR(255) NOT NULL,
    -- Rol asignado.
    id_rol BIGINT NOT NULL,
    -- Estado de cuenta.
    id_estado_usuario BIGINT NOT NULL,
    -- Fecha de creación.
    creado_en TIMESTAMP WITH TIME ZONE NOT NULL
        -- Fecha automática.
        DEFAULT CURRENT_TIMESTAMP,
    -- Última modificación.
    actualizado_en TIMESTAMP WITH TIME ZONE NOT NULL
        -- Fecha automática.
        DEFAULT CURRENT_TIMESTAMP,
    -- Control de concurrencia.
    version BIGINT NOT NULL DEFAULT 0,

    -- Impide duplicados.
    CONSTRAINT uk_usuario_correo UNIQUE (correo),

    -- Regla de validación.
    CONSTRAINT ck_usuario_correo_normalizado CHECK (
        -- Correo normalizado.
        correo = LOWER(BTRIM(correo))
        -- Correo no vacío.
        AND correo <> ''
    ),

    -- Relación entre tablas.
    CONSTRAINT fk_usuario_rol
        FOREIGN KEY (id_rol)
        -- Tabla de destino.
        REFERENCES db_autenticacion.rol (id),

    -- Relación entre tablas.
    CONSTRAINT fk_usuario_estado
        FOREIGN KEY (id_estado_usuario)
        -- Tabla de destino.
        REFERENCES db_autenticacion.estado_usuario (id)
);

-- Tabla de renovaciones.
CREATE TABLE db_autenticacion.token_renovacion (
    -- Identificador único.
    id UUID PRIMARY KEY,
    -- Usuario propietario.
    id_usuario UUID NOT NULL,
    -- Hash del token.
    token_hash VARCHAR(64) NOT NULL,
    -- Grupo de renovaciones.
    familia_id UUID NOT NULL,
    -- Fecha de creación.
    creado_en TIMESTAMP WITH TIME ZONE NOT NULL
        -- Fecha automática.
        DEFAULT CURRENT_TIMESTAMP,
    -- Fecha de vencimiento.
    expira_en TIMESTAMP WITH TIME ZONE NOT NULL,
    -- Fecha de revocación.
    revocado_en TIMESTAMP WITH TIME ZONE,
    -- Token de reemplazo.
    reemplazado_por UUID,
    -- Control de concurrencia.
    version BIGINT NOT NULL DEFAULT 0,

    -- Impide duplicados.
    CONSTRAINT uk_token_renovacion_hash UNIQUE (token_hash),

    -- Regla de validación.
    CONSTRAINT ck_token_renovacion_expiracion CHECK (
        -- Vencimiento posterior a creación.
        expira_en > creado_en
    ),

    -- Relación entre tablas.
    CONSTRAINT fk_token_renovacion_usuario
        FOREIGN KEY (id_usuario)
        -- Tabla de destino.
        REFERENCES db_autenticacion.usuario (id),

    -- Relación entre tablas.
    CONSTRAINT fk_token_renovacion_reemplazo
        FOREIGN KEY (reemplazado_por)
        -- Tabla de destino.
        REFERENCES db_autenticacion.token_renovacion (id)
);
